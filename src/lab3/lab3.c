// Задание 2.1 Создайте динамический двухмерный массив с размерностями,
// вычисляемыми в процессе выполнения программы - N*M.
// Задайте значения элементов помощью генератора [псевдо]случайных чисел.
// Найдите сумму элементов.
// Подсказка: для генерации [псевдо]случайных чисел используйте функцию
// стандартной библиотеки rand() (<stdlib.h>)
//
// Задание 2.2 В сформированном массиве отсортируйте каждую строку по
// убыванию значений. Используйте сортировку "выбором"
//
// Задание 2.3 Объявите одномерный массив размерностью N.
// Присвойте i-му элементу одномерного массива
// среднее значение элементов i-ой строки двухмерного массива
// ---------------------------------------------------------------------------
void task2(void)
{
    printf("\n=== Задание 2. Динамический двухмерный массив ===\n");

    int nRows = 0;
    int nCols = 0;
    printf("Введите количество строк и столбцов (N M): ");
    if (scanf("%d %d", &nRows, &nCols) != 2 || nRows <= 0 || nCols <= 0) {
        printf("Некорректный ввод\n");
        return;
    }

    // 2.1 выделение памяти под двухмерный массив
    int **pMatrix = (int **)malloc((size_t)nRows * sizeof(int *));
    if (pMatrix == NULL) {
        printf("Ошибка выделения памяти\n");
        return;
    }
    for (int i = 0; i < nRows; i++) {
        pMatrix[i] = (int *)malloc((size_t)nCols * sizeof(int));
        if (pMatrix[i] == NULL) {
            printf("Ошибка выделения памяти\n");
            for (int k = 0; k < i; k++) {
                free(pMatrix[k]);
            }
            free(pMatrix);
            return;
        }
    }

    // заполнение случайными числами
    srand((unsigned)time(NULL));
    for (int i = 0; i < nRows; i++) {
        for (int j = 0; j < nCols; j++) {
            pMatrix[i][j] = rand() % 100; // значения от 0 до 99
        }
    }

    printf("Исходный массив:\n");
    printMatrix(pMatrix, nRows, nCols);

    long long sum = 0;
    for (int i = 0; i < nRows; i++) {
        for (int j = 0; j < nCols; j++) {
            sum += pMatrix[i][j];
        }
    }
    printf("Сумма элементов: %lld\n", sum);

    // 2.2 сортировка каждой строки по убыванию методом выбора
    for (int i = 0; i < nRows; i++) {
        for (int j = 0; j < nCols - 1; j++) {
            int maxIndex = j;
            for (int k = j + 1; k < nCols; k++) {
                if (pMatrix[i][k] > pMatrix[i][maxIndex]) {
                    maxIndex = k;
                }
            }
            if (maxIndex != j) {
                int temp = pMatrix[i][j];
                pMatrix[i][j] = pMatrix[i][maxIndex];
                pMatrix[i][maxIndex] = temp;
            }
        }
    }

    printf("Массив после сортировки каждой строки по убыванию:\n");
    printMatrix(pMatrix, nRows, nCols);

    // 2.3 одномерный массив средних значений по строкам
    double *pAverages = (double *)malloc((size_t)nRows * sizeof(double));
    if (pAverages == NULL) {
        printf("Ошибка выделения памяти\n");
        for (int i = 0; i < nRows; i++) {
            free(pMatrix[i]);
        }
        free(pMatrix);
        return;
    }

    for (int i = 0; i < nRows; i++) {
        double rowSum = 0.0;
        for (int j = 0; j < nCols; j++) {
            rowSum += pMatrix[i][j];
        }
        pAverages[i] = rowSum / nCols;
    }

    printf("Средние значения по строкам: ");
    for (int i = 0; i < nRows; i++) {
        printf("%.2f", pAverages[i]);
        if (i < nRows - 1) {
            printf(" ");
        }
    }
    printf("\n");

    // освобождение памяти
    free(pAverages);
    for (int i = 0; i < nRows; i++) {
        free(pMatrix[i]);
    }
    free(pMatrix);
}

