// Задание 3.2 Простой поиск.
// Модифицируйте предыдущее задание следующим образом: очередное значение
// вводится в массив только при условии, что там еще такого нет (т.е. дубли
// игнорируются)
// ---------------------------------------------------------------------------
void task3_2(void)
{
    printf("\n=== Задание 3.2. Сортировка массива при вводе без дублей ===\n");

    int nCount = 0;
    printf("Введите количество чисел N: ");
    if (scanf("%d", &nCount) != 1 || nCount <= 0 || nCount > ARR_MAX) {
        printf("Некорректный ввод\n");
        return;
    }

    int arr[ARR_MAX];
    int len = 0;

    for (int i = 0; i < nCount; i++) {
        int value = 0;
        printf("Введите число %d из %d: ", i + 1, nCount);
        if (scanf("%d", &value) != 1) {
            printf("Некорректный ввод\n");
            return;
        }

        // дубликаты игнорируются
        if (containsValue(arr, len, value)) {
            printf("Значение %d уже есть в массиве, пропускаем\n", value);
            continue;
        }

        arr[len] = value;
        len++;
        sortAscending(arr, len);
        printf("Текущий массив: ");
        printArray(arr, len);
    }
}

