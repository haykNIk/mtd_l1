// Задание 4. Напишите программу, которая
// вводит строки с клавиатуры в двумерный встроенный массив 5*80 элементов
// типа char; признаком конца ввода является символ * (то есть строка - "*")
// или заполнение массива (больше свободных строк нет); затем производится
// сортировка строк в алфавитном порядке. Пояснение: не следует для
// сортировки сложных объектов физически перемещать их в памяти. Намного
// эффективнее завести массив указателей на соответствующие строки и
// перемещать только указатели.
//
// Подсказка: для лексиграфического сравнения строк пользуйтесь
// функцией стандартной библиотеки strcmp(...) (<string.h>).
// ---------------------------------------------------------------------------
void task4(void)
{
    printf("\n=== Задание 4. Сортировка строк ===\n");

    char lines[MAX_LINES][MAX_LEN]; // двумерный встроенный массив 5*80
    char *pLines[MAX_LINES];        // массив указателей на строки
    int count = 0;

    printf("Вводите строки (признак конца ввода - строка \"*\"):\n");
    for (int i = 0; i < MAX_LINES; i++) {
        printf("Строка %d: ", i + 1);
        if (scanf(" %79[^\n]", lines[i]) != 1) {
            break;
        }
        if (strcmp(lines[i], "*") == 0) {
            break; // конец ввода
        }
        pLines[count] = lines[i]; // сохраняем адрес строки, а не копию
        count++;
    }

    if (count == 0) {
        printf("Нет строк для сортировки\n");
        return;
    }

    // сортируем массив указателей: сами строки в памяти не перемещаются
    for (int i = 0; i < count - 1; i++) {
        int minIndex = i;
        for (int j = i + 1; j < count; j++) {
            if (strcmp(pLines[j], pLines[minIndex]) < 0) {
                minIndex = j;
            }
        }
        if (minIndex != i) {
            char *temp = pLines[i];
            pLines[i] = pLines[minIndex];
            pLines[minIndex] = temp;
        }
    }

    printf("Строки в алфавитном порядке:\n");
    for (int i = 0; i < count; i++) {
        printf("  %s\n", pLines[i]);
    }
}

