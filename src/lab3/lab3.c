// Задание 3.1 Напишите фрагмент кода, который вводит N целых чисел с
// клавиатуры в объявленный Вами встроенный одномерный массив, каждый раз
// упорядочивая полученный на предыдущем шаге массив по возрастанию и выводя
// на экран
// ---------------------------------------------------------------------------
void task3_1(void)
{
    printf("\n=== Задание 3.1. Сортировка массива при вводе ===\n");

    int nCount = 0;
    printf("Введите количество чисел N: ");
    if (scanf("%d", &nCount) != 1 || nCount <= 0 || nCount > ARR_MAX) {
        printf("Некорректный ввод\n");
        return;
    }

    int arr[ARR_MAX]; // встроенный (статический) одномерный массив
    int len = 0;

    for (int i = 0; i < nCount; i++) {
        int value = 0;
        printf("Введите число %d из %d: ", i + 1, nCount);
        if (scanf("%d", &value) != 1) {
            printf("Некорректный ввод\n");
            return;
        }
        arr[len] = value;
        len++;
        sortAscending(arr, len); // упорядочиваем накопленный массив по возрастанию
        printf("Текущий массив: ");
        printArray(arr, len);
    }
}

