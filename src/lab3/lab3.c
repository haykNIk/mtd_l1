#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

// размерности трехмерного статического массива
#define N3D 3
#define M3D 3
#define K3D 3

// максимальный размер одномерного массива (задание 3)
#define ARR_MAX 100

// количество строк и длина строки в двумерном массиве char (задание 4)
#define MAX_LINES 5
#define MAX_LEN 80

// ---------------------------------------------------------------------------
// Вспомогательные функции
// ---------------------------------------------------------------------------

// вывод двухмерного динамического массива
void printMatrix(int **matrix, int rows, int cols)
{
    for (int i = 0; i < rows; i++) {
        for (int j = 0; j < cols; j++) {
            printf("%4d", matrix[i][j]);
        }
        printf("\n");
    }
}

// вывод одномерного массива через пробел
void printArray(const int *arr, int len)
{
    for (int i = 0; i < len; i++) {
        printf("%d", arr[i]);
        if (i < len - 1) {
            printf(" ");
        }
    }
    printf("\n");
}

// сортировка одномерного массива по возрастанию методом вставок
void sortAscending(int *arr, int len)
{
    for (int i = 1; i < len; i++) {
        int key = arr[i];
        int j = i - 1;
        while (j >= 0 && arr[j] > key) {
            arr[j + 1] = arr[j];
            j--;
        }
        arr[j + 1] = key;
    }
}

// проверка наличия значения в массиве (простой поиск)
int containsValue(const int *arr, int len, int value)
{
    for (int i = 0; i < len; i++) {
        if (arr[i] == value) {
            return 1;
        }
    }
    return 0;
}

